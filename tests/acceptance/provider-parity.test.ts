/* ---- Fixtures ---- */

const MESSAGES: ProviderMessage[] = [
  { role: 'system', content: 'sys' },
  { role: 'user', content: 'hi' },
  { role: 'assistant', content: 'prev' },
  { role: 'user', content: 'again' }
]

interface Captured {
  url: string
  headers: Record<string, string>
  body: Record<string, unknown>
  hasSignal: boolean
}

function frame(payload: unknown): string {
  return `data: ${JSON.stringify(payload)}\n\n`
}

/** OpenAI-wire stream: one content delta per text, finish_reason on the last, then [DONE]. */
function openAiFrames(texts: string[]): string[] {
  const frames = texts.map((text, index) =>
    frame({
      id: 'chatcmpl-1',
      object: 'chat.completion.chunk',
      created: 1,
      model: 'test-model',
      choices: [
        {
          index: 0,
          delta: { content: text },
          finish_reason: index === texts.length - 1 ? 'stop' : null
        }
      ]
    })
  )
  return [...frames, 'data: [DONE]\n\n']
}

function sseResponse(frames: string[], splitAt?: number): Response {
  const encoder = new TextEncoder()
  const body = new ReadableStream<Uint8Array>({
    start(controller) {
      if (splitAt !== undefined) {
        const joined = frames.join('')
        controller.enqueue(encoder.encode(joined.slice(0, splitAt)))
        controller.enqueue(encoder.encode(joined.slice(splitAt)))
      } else {
        for (const item of frames) controller.enqueue(encoder.encode(item))
      }
      controller.close()
    }
  })
  return new Response(body, { status: 200, headers: { 'Content-Type': 'text/event-stream' } })
}

interface CaptureOptions {
  status?: number
  errorBody?: string
  splitAt?: number
}

function captureFetch(frames: string[], options: CaptureOptions = {}): Captured[] {
  const calls: Captured[] = []
  const impl = vi.fn(async (input: unknown, init?: RequestInit): Promise<Response> => {
    const headers: Record<string, string> = {}
    new Headers(init?.headers ?? {}).forEach((value, key) => {
      headers[key.toLowerCase()] = value
    })
    const rawBody = typeof init?.body === 'string' ? init.body : '{}'
    calls.push({
      url: String(input),
      headers,
      body: JSON.parse(rawBody) as Record<string, unknown>,
      hasSignal: init?.signal instanceof AbortSignal
    })

    if (options.status && options.status >= 400) {
      return new Response(options.errorBody ?? '{"error":{"message":"boom"}}', {
        status: options.status,
        headers: { 'Content-Type': 'application/json' }
      })
    }
    return sseResponse(frames, options.splitAt)
  })
  vi.stubGlobal('fetch', impl)
  return calls
}

async function collect(generator: AsyncGenerator<string>): Promise<string> {
  let text = ''
  for await (const chunk of generator) text += chunk
  return text
}

function role(connection: Record<string, unknown>, model: string): void {
  resolveRole.mockReturnValue({ connection, model })
}

/** Every route, for the uniform-shape sweep. */
const ROUTE_CASES: Array<{ providerType: string; connection: Record<string, unknown> }> = [
  {
    providerType: 'openai-compatible',
    connection: { apiKey: 'test-token-a', baseUrl: 'https://gw.test/v1' }
  },
  { providerType: 'openai', connection: { apiKey: 'test-token-b' } },
  { providerType: 'openrouter', connection: { apiKey: 'test-token-c' } },
  { providerType: 'google-ai-studio', connection: { apiKey: 'test-token-d' } },
  { providerType: 'ollama', connection: { host: 'http://localhost:11434' } }
]

beforeEach(() => {
  resolveRole.mockReset()
  vi.unstubAllGlobals()
})

/* ---- Parity: OpenAI-wire transport ---- */

describe('openai-wire transport parity', () => {
  it('openai-compatible posts the verbatim body to {baseUrl}/chat/completions', async () => {
    role(
      { providerType: 'openai-compatible', apiKey: 'test-token-a', baseUrl: 'https://gw.test/v1' },
      'm1'
    )
    const calls = captureFetch(openAiFrames(['Hel', 'lo']))

    await expect(collect(callProviderStream(MESSAGES, 'chat'))).resolves.toBe('Hello')
    expect(calls).toHaveLength(1)
    expect(calls[0].url).toBe('https://gw.test/v1/chat/completions')
    expect(calls[0].headers.authorization).toBe('Bearer test-token-a')
    expect(calls[0].body).toEqual({ model: 'm1', messages: MESSAGES, stream: true })
    expect(calls[0].hasSignal).toBe(true)
  })

  it('normalises a trailing slash on baseUrl', async () => {
    role(
      { providerType: 'openai-compatible', apiKey: 'test-token-a', baseUrl: 'https://gw.test/v1/' },
      'm1'
    )
    const calls = captureFetch(openAiFrames(['x']))

    await collect(callProviderStream(MESSAGES, 'chat'))
    expect(calls[0].url).toBe('https://gw.test/v1/chat/completions')
  })

  it('openai defaults to api.openai.com/v1', async () => {
    role({ providerType: 'openai', apiKey: 'test-token-b' }, 'gpt-x')
    const calls = captureFetch(openAiFrames(['x']))

    await collect(callProviderStream(MESSAGES, 'chat'))
    expect(calls[0].url).toBe('https://api.openai.com/v1/chat/completions')
    expect(calls[0].headers.authorization).toBe('Bearer test-token-b')
    expect(calls[0].body).toEqual({ model: 'gpt-x', messages: MESSAGES, stream: true })
  })

  it('openrouter defaults to openrouter.ai/api/v1', async () => {
    role({ providerType: 'openrouter', apiKey: 'test-token-c' }, 'vendor/model')
    const calls = captureFetch(openAiFrames(['x']))

    await collect(callProviderStream(MESSAGES, 'chat'))
    expect(calls[0].url).toBe('https://openrouter.ai/api/v1/chat/completions')
    expect(calls[0].body).toEqual({ model: 'vendor/model', messages: MESSAGES, stream: true })
  })

  it('ollama targets {host}/v1 without auth', async () => {
    role({ providerType: 'ollama', host: 'http://localhost:11434/' }, 'qwen3:4b')
    const calls = captureFetch(openAiFrames(['x']))

    await collect(callProviderStream(MESSAGES, 'chat'))
    expect(calls[0].url).toBe('http://localhost:11434/v1/chat/completions')
    expect(calls[0].headers.authorization).toBeUndefined()
    expect(calls[0].body).toEqual({ model: 'qwen3:4b', messages: MESSAGES, stream: true })
  })

  it('reassembles frames split across network chunks', async () => {
    role(
      { providerType: 'openai-compatible', apiKey: 'test-token-a', baseUrl: 'https://gw.test/v1' },
      'm1'
    )
    const joined = openAiFrames(['alpha', 'beta']).join('')
    captureFetch(openAiFrames(['alpha', 'beta']), { splitAt: joined.indexOf('"beta"') - 8 })

    await expect(collect(callProviderStream(MESSAGES, 'chat'))).resolves.toBe('alphabeta')
  })

  it('ignores blank and malformed frames instead of aborting the stream', async () => {
    role(
      { providerType: 'openai-compatible', apiKey: 'test-token-a', baseUrl: 'https://gw.test/v1' },
      'm1'
    )
    captureFetch([
      frame({ choices: [{ delta: { content: 'a' }, finish_reason: null }] }),
      'data:\n\n',
      'data: not-json\n\n',
      frame({ choices: [{ delta: { content: 'b' }, finish_reason: 'stop' }] }),
      'data: [DONE]\n\n'
    ])

    await expect(collect(callProviderStream(MESSAGES, 'chat'))).resolves.toBe('ab')
  })
})

/* ---- Uniformity: no provider gets special treatment ---- */

describe('uniform routing', () => {
  it('google uses its OpenAI-compatible endpoint with a bearer key', async () => {
    role({ providerType: 'google-ai-studio', apiKey: 'test-token-d' }, 'gemini-x')
    const calls = captureFetch(openAiFrames(['x']))

    await collect(callProviderStream(MESSAGES, 'chat'))
    expect(calls[0].url).toBe(
      'https://generativelanguage.googleapis.com/v1beta/openai/chat/completions'
    )
    expect(calls[0].headers.authorization).toBe('Bearer test-token-d')
  })

  it('sends the same body shape to every provider', async () => {
    const shapes: Array<{ providerType: string; keys: string[] }> = []

    for (const testCase of ROUTE_CASES) {
      role({ providerType: testCase.providerType, ...testCase.connection }, 'model-x')
      const calls = captureFetch(openAiFrames(['x']))
      await collect(callProviderStream(MESSAGES, 'chat'))
      shapes.push({ providerType: testCase.providerType, keys: Object.keys(calls[0].body).sort() })
    }

    expect(shapes).toHaveLength(ROUTE_CASES.length)
    for (const shape of shapes) {
      expect(shape.keys).toEqual(['messages', 'model', 'stream'])
    }
  })

  it('never injects a provider tool, even for a Google connection', async () => {
    role({ providerType: 'google-ai-studio', apiKey: 'test-token-d' }, 'gemini-x')
    const calls = captureFetch(openAiFrames(['x']))

    await collect(callProviderStream(MESSAGES, 'chat'))
    expect(calls[0].body.tools).toBeUndefined()
    expect(calls[0].body.tool_config).toBeUndefined()
  })

  it('has no provider-specific SDK or provider tool in the transport', () => {
    const source = readFileSync(join(process.cwd(), 'src/main/provider.ts'), 'utf-8')
    expect(source).not.toContain('@ai-sdk/google')
    expect(source).not.toMatch(/google ?search/i)
    expect(source).not.toContain('web_search')
    expect(source).toMatch(/ROUTES/)
  })
})

/* ---- Parity: error surfaces ---- */

describe('error parity', () => {
  it('reports a non-200 as "API error <status>: <body>" after a single attempt', async () => {
    role(
      { providerType: 'openai-compatible', apiKey: 'test-token-a', baseUrl: 'https://gw.test/v1' },
      'm1'
    )
    const calls = captureFetch([], { status: 500, errorBody: '{"error":{"message":"boom"}}' })

    await expect(collect(callProviderStream(MESSAGES, 'chat'))).rejects.toThrow(/^API error 500: /)
    expect(calls).toHaveLength(1)
  })

  it('rejects a connection without an api key', async () => {
    role({ providerType: 'openai' }, 'gpt-x')

    await expect(collect(callProviderStream(MESSAGES, 'chat'))).rejects.toThrow(
      /No API key configured/
    )
  })

  it('rejects an unassigned role', async () => {
    resolveRole.mockReturnValue(null)

    await expect(collect(callProviderStream(MESSAGES, 'chat'))).rejects.toMatchObject({
      name: 'RoleUnassignedError'
    })
  })

  it('rejects an unknown provider type', async () => {
    role({ providerType: 'mystery', apiKey: 'test-token-e' }, 'm1')

    await expect(collect(callProviderStream(MESSAGES, 'chat'))).rejects.toThrow(/not supported yet/)
  })

  it('requires a base url for openai-compatible', async () => {
    role({ providerType: 'openai-compatible', apiKey: 'test-token-a' }, 'm1')

    await expect(collect(callProviderStream(MESSAGES, 'chat'))).rejects.toThrow(
      /Base URL is required/
    )
  })

  it('callProvider drains the stream for non-streaming callers', async () => {
    role(
      { providerType: 'openai-compatible', apiKey: 'test-token-a', baseUrl: 'https://gw.test/v1' },
      'm1'
    )
    captureFetch(openAiFrames(['a', 'b']))

    await expect(callProvider(MESSAGES, 'chat')).resolves.toBe('ab')
  })
})

